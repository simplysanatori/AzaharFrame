#!/usr/bin/env python3
# Makes src/frame_xr/menu/md3_fonts.h: the fonts of the in-VR menu (frame_xr/menu), cut down to
# what the menu draws and embedded as base64, so nothing has to be found on the system.
#
#   Google Sans Flex (SIL Open Font License 1.1, no Reserved Font Name): static instances at
#     weight 400 (body) and 500 (labels, titles), Latin text only.
#   Material Symbols Rounded (Apache License 2.0): static instances unfilled (FILL 0) and filled
#     (FILL 1) at weight 400, grade 0, optical size 24, only the icons in ICONS.
#
# Needs fontTools (pip install fonttools). The source fonts are downloaded by hand from
#   https://github.com/google/fonts/tree/main/ofl/googlesansflex
#   https://github.com/google/material-design-icons/tree/master/variablefont
# and passed as arguments:
#   make-md3-fonts.py GoogleSansFlex[...].ttf MaterialSymbolsRounded[...].ttf \
#       MaterialSymbolsRounded[...].codepoints src/frame_xr/menu/md3_fonts.h
import base64
import io
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

# The icons the menu uses (Material Symbols names). Add a name here and run the script again.
ICONS = [
    "home", "open_with", "monitoring", "stadia_controller", "settings",
    "play_arrow", "save", "history", "save_as", "folder_open", "photo_camera", "restart_alt",
    "close", "open_in_new", "swap_vert", "recenter", "check", "arrow_drop_down",
    "chevron_right", "info", "arrow_back", "visibility", "visibility_off", "add", "remove",
    "fit_screen", "aspect_ratio", "view_in_ar", "speed", "tune", "tv", "code", "edit",
    # AzaharFrame cheatstab: the Cheats tab
    "star", "verified", "cloud_download", "cloud_off", "download", "refresh",
    # AzaharFrame cheatstab: the Mods tab
    "extension",
    # AzaharFrame texui: the Mods tab's Textures segment
    "texture",
]

# Text: printable ASCII and the few other characters the labels and values use.
TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + "°×–—…·’“”"


def cut(font, unicodes, features):
    opts = subset.Options()
    opts.layout_features = features
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]  # copyright, names, version, licence
    opts.name_languages = [0x409]
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=unicodes)
    s.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def text_font(path, weight):
    f = TTFont(path)
    f = instancer.instantiateVariableFont(
        f, {"wght": weight, "opsz": 18, "wdth": 100, "slnt": 0, "ROND": 0}, updateFontNames=False)
    return cut(f, [ord(c) for c in TEXT], ["kern"])


def icon_font(path, fill, codes):
    f = TTFont(path)
    f = instancer.instantiateVariableFont(f, {"FILL": fill, "wght": 400, "GRAD": 0, "opsz": 24})
    return cut(f, codes, [])


def blob(name, data):
    b = base64.b64encode(data).decode()
    lines = [b[i:i + 100] for i in range(0, len(b), 100)]
    body = "\n".join(f'    "{l}"' for l in lines)
    return f"// {len(data)} bytes\ninline constexpr const char {name}[] =\n{body};\n"


def main():
    sans, symbols, codepoints, out = sys.argv[1:5]
    table = {}
    for line in open(codepoints, encoding="utf-8"):
        n, c = line.split()
        table.setdefault(n, int(c, 16))
    missing = [n for n in ICONS if n not in table]
    if missing:
        sys.exit(f"not in the codepoints file: {missing}")
    codes = sorted({table[n] for n in ICONS})
    parts = [
        "// Generated by steam-frame/dev/make-md3-fonts.py: do not edit.\n"
        "// Google Sans Flex: Copyright 2015 The Google Sans Flex Authors\n"
        "// (https://github.com/googlefonts/googlesans-flex), licensed under the SIL Open Font License,\n"
        "// Version 1.1 (https://openfontlicense.org). Static instances, Latin subset.\n"
        "// Material Symbols Rounded: Copyright Google LLC, licensed under the Apache License, Version 2.0\n"
        "// (https://www.apache.org/licenses/LICENSE-2.0). Static instances, subset to the icons below.\n"
        "#pragma once\n\nnamespace FrameXr::Menu::Fonts {\n\n",
        blob("kSans400", text_font(sans, 400)), "\n",
        blob("kSans500", text_font(sans, 500)), "\n",
        blob("kSymbols", icon_font(symbols, 0, codes)), "\n",
        blob("kSymbolsFilled", icon_font(symbols, 1, codes)), "\n",
        "} // namespace FrameXr::Menu::Fonts\n\nnamespace FrameXr::Menu::Icon {\n",
    ]
    for n in ICONS:
        ident = "k" + "".join(w.capitalize() for w in n.split("_"))
        parts.append(f"inline constexpr char32_t {ident} = 0x{table[n]:04X}; // {n}\n")
    parts.append("} // namespace FrameXr::Menu::Icon\n")
    with open(out, "w", encoding="utf-8") as f:
        f.write("".join(parts))


if __name__ == "__main__":
    main()
